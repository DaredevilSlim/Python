# В этой главе:
# - Преимущества списков перед кортежами и кортежей перед списками
# - Сортировка списков, состоящих из составных типов данных
# - Использование именованных кортежей как модели контейнера данных
# - Обращение к данным словаря
# - Хешируемость и ее последствия для словарей и множеств
# - Применение операций над множествами при работе с данными других типов

# Python как язык программирования общего назначения предоставляет диапазон встроенных типов данных для разных целей,
# включая типы коллекций. Типы коллекций служат контейнерами для хранения целых чисел, строк, экземпляров
# пользовательских классов и других видов объектов. В любом проекте нам приходится работать с несколькими объектами
# одновременно, а в таких ситуациях часто возникает необходимость в контейнерах данных.
# В каждом современном языке программирования контейнеры являются одной из базовых моделей данных, что подчеркивает их
# важность как структурных элементов для любого программного проекта. В главе 14 показано, как при построении
# таск-менеджера контейнеры данных будут использоваться для разных целей: списки list, например, для хранения
# экземпляров пользовательского класса Task (глава 8). В этой главе рассматриваются самые распространенные встроенные
# контейнеры данных, включая списки, кортежи, словари и множества.
# Я не пытаюсь привести здесь исчерпывающий обзор всей функциональности, относящейся к этим моделям данных.
# Мы сосредоточимся на фундаментальных темах, особенно важных для наших проектов.
# ОСНОВНЫЕ ПОНЯТИЯ:
# Контейнеры данных, например списки и кортежи, представляют собой объекты, которые содержат другие объекты. Строки и
# целые числа, наоборот, не являются контейнерами данных, так как они не содержат другие объекты.


# 3.1. КАК ВЫБРАТЬ МЕЖДУ СПИСКОМ И КОРТЕЖЕМ
print('3.1. КАК ВЫБРАТЬ МЕЖДУ СПИСКОМ И КОРТЕЖЕМ')
# Списки и кортежи часто рассматриваются вместе, что объясняется их сходством как контейнеров данных. И те и другие
# могут хранить упорядоченные наборы объектов, к которым можно обращаться по индексам. Во многих случаях они
# используются взаимозаменяемо, но в некоторых ситуациях приходится выбирать один из двух видов контейнеров. Допустим,
# вам нужен контейнер данных для хранения информации об операциях с банковским счетом. Что использовать — список или
# кортеж? Или другой пример: какой контейнер лучше подойдет для вывода информации об операции транзакции (скажем, суммы
# и даты) — список или кортеж?
# Существует множество подобных сценариев, в которых оба варианта представляются возможными, но в конечном итоге мы
# выбираем один из них. В этом разделе рассматриваются ключевые различия между списками и кортежами, влияющие на выбор
# одного из контейнеров.


# 3.1.1. Кортежи для неизменяемых данных, списки — для изменяемых данных
print('3.1.1. Кортежи для неизменяемых данных, списки — для изменяемых данных')
# Принципиальное различие между списками и кортежами — изменяемость (mutability). Списки являются изменяемыми в том
# смысле, что данные объекта list можно изменить: вы можете присоединить новые элементы к концу списка, вставить
# элементы в середину, изменить и удалить элементы. Для обеспечения изменяемости Python предоставляет набор методов в
# классе list: append, extend, remove и т.д., которые следует знать.
# Основные операции со списками как изменяемыми объектами:
numbers = [1, 2, 3]         # Создание списка - [1, 2, 3]
numbers.insert(0, 0)         # Вставка элемента по заданному индексу - [0, 1, 2, 3]
numbers.append(4)           # Присоединение элемента в конец списка - [0, 1, 2, 3, 4]
numbers.extend ([5, 6, 7])  # Расширение списка несколькими элементами - [0, 1, 2, 3, 4, 5, 6, 7]
numbers.remove (5)          # Удаление элемента по значению - [0, 1, 2, 3, 4, 6, 7]
del numbers[3]              # Удаление элемента с заданным индексом - [0, 1, 2, 4, 6, 7]
# ОБРАТИТЕ ВНИМАНИЕ:
# Метод списков remove удаляет только первый подходящий элемент. Если удаляемый элемент отсутствует в списке, происходит
# ошибка ValueError.
# В отличие от списков, кортежи неизменяемы; изменить данные объекта tuple невозможно. Чтобы обеспечить неизменяемость и
# предотвратить возможную путаницу, Python не предоставляет методов для изменения объектов tuple. Изменить элементы
# кортежа синтаксически возможно, но такое действие приводит к исключению: вызов несуществующего метода приводит к
# ошибке AttributeError, а повторное присваивание элементу кортежа — к ошибке TypeError, как показано
# в листинге 3.1 (test_0010.py).
# Из-за разницы в изменяемости следует использовать списки, а не кортежи, если вы намерены обновлять данные.
# В таск-менеджере задачи хранятся в списках, потому что мы добавляем новые или удаляем старые задачи. Если хранимые
# данные не изменяются, лучше использовать неизменяемые кортежи. Метаданные задачи в таск-менеджере (например, время
# создания и пользователь) могут храниться в кортежах, потому что эти метаданные остаются фиксированными.
# И хотя списки могут применяться везде, где применяются кортежи, есть ряд случаев, когда мы отдаем предпочтение
# кортежам перед списками:
# - Предотвращение неожиданных изменений в данных. Попытка изменения данных кортежа приводит к ошибке AttributeError или
# TypeError (листинг 3.1) (test_0010.py).
# - Явное выражение намерения сохранить данные в неизменном виде. Мы используем для хранения информации о задаче
# (creation_time, user) вместо [creation_time, user], показывая, что эти два значения фиксируются в программе.
# - Более эффективное расходование памяти кортежами по сравнению со списками. Если список и кортеж содержат одинаковые
# данные, список занимает больше памяти, чем кортеж. Большие затраты памяти для списков обусловлены необходимостью
# поддерживать изменяемость. Таким образом, в ситуациях, требующих хранения множества экземпляров, мы предпочитаем
# использовать кортежи ради более экономного расходования памяти.
